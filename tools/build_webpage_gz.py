#!/usr/bin/env python3
"""
Compress WebPage.html (or extract from WebPage.h) into WebPageGz.h for ESP32.
Saves ~170 KB of Flash PROGMEM and speeds up web page load times 4-5x.
"""
import os
import re
import gzip

BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC_DIR = os.path.join(BASE_DIR, "MeteoPlaneRadar")
PAGE_H = os.path.join(SRC_DIR, "WebPage.h")
PAGE_HTML = os.path.join(SRC_DIR, "WebPage.html")
PAGE_GZ_H = os.path.join(SRC_DIR, "WebPageGz.h")

def main():
    if os.path.exists(PAGE_HTML):
        with open(PAGE_HTML, "rb") as f:
            raw_data = f.read()
    elif os.path.exists(PAGE_H):
        with open(PAGE_H, "rb") as f:
            content = f.read()
        match = re.search(rb'R"rawliteral\((.*?)\)rawliteral"', content, re.DOTALL)
        if not match:
            raise ValueError("Could not extract R\"rawliteral(...) from WebPage.h")
        raw_data = match.group(1)
        # Also save WebPage.html for clean source editing
        with open(PAGE_HTML, "wb") as f:
            f.write(raw_data)
        print(f"Extracted clean HTML to {PAGE_HTML}")
    else:
        raise FileNotFoundError("Neither WebPage.html nor WebPage.h found")

    gz_data = gzip.compress(raw_data, compresslevel=9, mtime=0)
    raw_len = len(raw_data)
    gz_len = len(gz_data)
    saved = raw_len - gz_len
    ratio = (gz_len / raw_len) * 100

    print(f"Original HTML:   {raw_len:,} bytes")
    print(f"Gzip Compressed: {gz_len:,} bytes ({ratio:.1f}%, saved {saved:,} bytes / {saved/1024:.1f} KB)")

    # Format C array
    hex_lines = []
    line = []
    for i, b in enumerate(gz_data):
        line.append(f"0x{b:02x}")
        if len(line) == 16 or i == gz_len - 1:
            hex_lines.append("  " + ", ".join(line) + ",")
            line = []

    header_content = f"""// =============================================================================
//  MeteoPlaneRadar
//  WebPageGz.h - Pre-compressed Web UI (gzip level 9).
//  Auto-generated by tools/build_webpage_gz.py. DO NOT EDIT DIRECTLY.
//  Edit MeteoPlaneRadar/WebPage.html and run python tools/build_webpage_gz.py.
//
//  Original Size:   {raw_len:,} bytes ({raw_len/1024:.1f} KB)
//  Compressed Size: {gz_len:,} bytes ({gz_len/1024:.1f} KB) - {saved/1024:.1f} KB saved
// =============================================================================
#pragma once
#include <Arduino.h>

const size_t PAGE_HTML_GZ_LEN = {gz_len};

static const uint8_t PAGE_HTML_GZ[{gz_len}] PROGMEM = {{
{chr(10).join(hex_lines)}
}};
"""

    with open(PAGE_GZ_H, "w", encoding="utf-8") as f:
        f.write(header_content)

    print(f"Successfully generated {PAGE_GZ_H}")

if __name__ == "__main__":
    main()
